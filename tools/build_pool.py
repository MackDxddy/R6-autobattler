"""Builds pool.js for the battler: the players the shop can offer.

One card per Tier 1 player (30+ kills), from their most recent season in data/R6_Stats_primary_roles.csv.
Mains: their latest attack/defense op if it's in the game; otherwise the most recent in-game op
from an earlier season; otherwise a default for their role. Rarity comes from rarity.js (build_rarity.py).

Run:  python tools/build_pool.py
"""
import csv, json, os, re

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, '..', 'data', 'R6_Stats_primary_roles.csv')
PREP = os.path.join(HERE, '..', 'public', 'prep.html')
OUT = os.path.join(HERE, '..', 'public', 'pool.js')
MIN_KILLS = 30  # latest season needs at least this many kills

# Ops that exist in the game (from prep.html's OPS table) and which side they're on
prep = open(PREP, encoding='utf-8').read()
i = prep.index('const OPS = {'); j = prep.index('\n};', i)
OPS = dict(re.findall(r"(\w+):\['[^']*','(\w+)'\]", prep[i:j]))  # id -> lane
ATTACK_LANES = {'Entry', 'Flank', 'Support'}
DEFAULT = {  # role -> (attack, defense) when none of their ops are in the game
    'Entry': ('ash', 'vigil'), 'Flex': ('buck', 'smoke'), 'IGL': ('thatcher', 'mute'), 'Support': ('thatcher', 'mute'),
}


def norm(op):
    return re.sub(r'[^a-z]', '', op.lower().replace('ä', 'a'))


def num(x):
    try:
        return float(str(x).strip().rstrip('%'))
    except ValueError:
        return 0.0


seasons = {}
with open(SRC, encoding='utf-8') as f:
    for r in csv.DictReader(f):
        if r['Tier 1'] != 'Yes':
            continue
        seasons.setdefault(r['Player'].strip(), []).append(r)

pool = []
for name, rows in seasons.items():
    rows.sort(key=lambda r: int(r['Year'] or 0), reverse=True)
    r = rows[0]
    if int((r['KD (+/-)'] or '0-0').split('-')[0] or 0) < MIN_KILLS:
        continue  # too small a sample to make a card from

    def pick(col, side_ok, fallback):
        for s in rows:  # newest first
            o = norm(s[col])
            if o in OPS and side_ok(OPS[o]):
                return o
        return fallback

    role = r['Role'] if r['Role'] in DEFAULT else 'Flex'
    atk = pick('Atk', lambda lane: lane in ATTACK_LANES, DEFAULT[role][0])
    dfn = pick('Def', lambda lane: lane not in ATTACK_LANES, DEFAULT[role][1])
    pool.append([
        name, int(r['Year']), num(r['Rating']), r['KD (+/-)'].split(' ')[0], r['Entry (+/-)'],
        round(num(r['SRV'])), int(num(r['1vX'])), int(num(r['Plants'])), round(num(r['HS%'])),
        atk, dfn, [role], round(num(r['WinRate']), 3),
    ])

pool.sort(key=lambda p: p[0].lower())
with open(OUT, 'w', encoding='utf-8') as f:
    f.write('// Generated by build_pool.py from data/R6_Stats_primary_roles.csv. Do not edit by hand.\n')
    f.write('// [name, year, rating, K-D, entry (+/-), SRV%, clutches, plants, HS%, attack main, defense main, [role], win rate]\n')
    f.write('window.POOL_DATA = ' + json.dumps(pool, ensure_ascii=False, separators=(',', ':')) + ';\n')
print(len(pool), 'players ->', OUT)
